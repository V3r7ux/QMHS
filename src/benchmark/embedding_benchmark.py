from __future__ import annotations

import csv
from dataclasses import dataclass, field, asdict
from pathlib import Path
from typing import Any


@dataclass(slots=True)
class EmbeddingBenchmarkRecord:
    """
    Stores the embedding-feasibility statistics for a single QUBO/BQM.

    Each record corresponds to one logical problem Hamiltonian generated by an
    algorithm and tested against an ideal hardware topology, such as Pegasus,
    Zephyr, or Chimera.

    For algorithms that generate multiple QUBOs internally, such as
    cardinality sweep or recursive PUBO, the optional fields target_cardinality,
    iteration, and stage can be used to identify the specific QUBO being tested.
    """

    problem_id: str
    algorithm: str
    universe_size: int
    num_test_cases: int

    embedding_found: bool

    num_logical_variables: int
    num_logical_couplers: int

    num_physical_qubits: int | None
    max_chain_length: int | None
    min_chain_length: int | None
    mean_chain_length: float | None
    physical_logical_qubit_ratio: float | None

    topology: str
    topology_size: int
    target_num_nodes: int
    target_num_edges: int

    num_tries: int
    successful_tries: int
    runtime_seconds: float

    target_cardinality: int | None = None
    iteration: int | None = None
    stage: str | None = None


@dataclass(slots=True)
class EmbeddingAttemptRecord:
    """
    Stores the result of a single minorminer attempt.

    This record is optional and is mainly useful for debugging or for studying
    how stable the embedding search is across repeated heuristic attempts.
    """

    problem_id: str
    algorithm: str
    universe_size: int
    num_test_cases: int

    attempt_id: int
    embedding_found: bool
    runtime_seconds: float

    num_physical_qubits: int | None
    max_chain_length: int | None
    mean_chain_length: float | None

    topology: str
    topology_size: int

    target_cardinality: int | None = None
    iteration: int | None = None
    stage: str | None = None


@dataclass(slots=True)
class EmbeddingBenchmarkRecordSet:
    """
    Collects embedding-feasibility benchmark records.

    The class stores one main record for each tested QUBO/BQM and, optionally,
    one record for each individual minorminer attempt. The records can then be
    exported to CSV files for aggregation and plotting.
    """

    embedding_records: list[EmbeddingBenchmarkRecord] = field(default_factory=list)
    attempt_records: list[EmbeddingAttemptRecord] = field(default_factory=list)

    def add_embedding_result(
        self,
        problem_id: str,
        algorithm: str,
        universe_size: int,
        num_test_cases: int,
        metadata: dict[str, Any],
        target_cardinality: int | None = None,
        iteration: int | None = None,
        stage: str | None = None,
        store_attempts: bool = True,
    ) -> None:
        """
        Add the embedding metadata of one simulator call to the benchmark.

        This method expects the metadata dictionary produced by
        EmbeddingFeasibilitySimulator. It extracts the global embedding
        statistics and appends them to embedding_records.

        If store_attempts is True, the method also extracts per-attempt
        minorminer statistics and appends them to attempt_records.
        """

        self.embedding_records.append(
            EmbeddingBenchmarkRecord(
                problem_id=problem_id,
                algorithm=algorithm,
                universe_size=universe_size,
                num_test_cases=num_test_cases,
                embedding_found=metadata["embedding_found"],
                num_logical_variables=metadata["num_logical_variables"],
                num_logical_couplers=metadata["num_logical_couplers"],
                num_physical_qubits=metadata["num_physical_qubits"],
                max_chain_length=metadata["max_chain_length"],
                min_chain_length=metadata["min_chain_length"],
                mean_chain_length=metadata["mean_chain_length"],
                physical_logical_qubit_ratio=metadata[
                    "physical_logical_qubit_ratio"
                ],
                topology=metadata["topology"],
                topology_size=metadata["topology_size"],
                target_num_nodes=metadata["target_num_nodes"],
                target_num_edges=metadata["target_num_edges"],
                num_tries=metadata["num_tries"],
                successful_tries=metadata["successful_tries"],
                runtime_seconds=metadata["runtime"],
                target_cardinality=target_cardinality,
                iteration=iteration,
                stage=stage,
            )
        )

        if store_attempts:
            self._add_attempt_results(
                problem_id=problem_id,
                algorithm=algorithm,
                universe_size=universe_size,
                num_test_cases=num_test_cases,
                metadata=metadata,
                target_cardinality=target_cardinality,
                iteration=iteration,
                stage=stage,
            )

    def _add_attempt_results(
        self,
        problem_id: str,
        algorithm: str,
        universe_size: int,
        num_test_cases: int,
        metadata: dict[str, Any],
        target_cardinality: int | None,
        iteration: int | None,
        stage: str | None,
    ) -> None:
        """
        Add the per-attempt embedding results stored in the simulator metadata.

        Each attempt corresponds to one independent call to minorminer. These
        records are useful to measure how often minorminer succeeds and how
        much the embedding quality varies between attempts.
        """

        attempts = metadata.get("attempts", [])

        for attempt in attempts:
            self.attempt_records.append(
                EmbeddingAttemptRecord(
                    problem_id=problem_id,
                    algorithm=algorithm,
                    universe_size=universe_size,
                    num_test_cases=num_test_cases,
                    attempt_id=attempt["attempt_id"],
                    embedding_found=attempt["embedding_found"],
                    runtime_seconds=attempt["runtime"],
                    num_physical_qubits=attempt["num_physical_qubits"],
                    max_chain_length=attempt["max_chain_length"],
                    mean_chain_length=attempt["mean_chain_length"],
                    topology=metadata["topology"],
                    topology_size=metadata["topology_size"],
                    target_cardinality=target_cardinality,
                    iteration=iteration,
                    stage=stage,
                )
            )

    def add_result_set_metadata(
        self,
        problem_id: str,
        algorithm: str,
        universe_size: int,
        num_test_cases: int,
        result_metadata: dict[str, Any],
        store_attempts: bool = True,
    ) -> None:
        """
        Add embedding metadata from an algorithm-level ResultSet.

        This helper is useful when the algorithm stores simulator metadata in
        nested dictionaries. It supports two common cases:

        1. A single QUBO metadata dictionary, containing embedding_found.
        2. Multiple nested metadata dictionaries indexed by cardinality,
           iteration, or another stage key.

        The method tries to infer the structure automatically.
        """

        if "embedding_found" in result_metadata:
            self.add_embedding_result(
                problem_id=problem_id,
                algorithm=algorithm,
                universe_size=universe_size,
                num_test_cases=num_test_cases,
                metadata=result_metadata,
                store_attempts=store_attempts,
            )
            return

        for key, value in result_metadata.items():
            if not isinstance(value, dict):
                continue

            simulator_metadata = value.get("simulator_metadata", value)

            if not isinstance(simulator_metadata, dict):
                continue

            if "embedding_found" not in simulator_metadata:
                continue

            target_cardinality = self._infer_target_cardinality(key, value)
            iteration = self._infer_iteration(key, value)
            stage = self._infer_stage(key, value)

            self.add_embedding_result(
                problem_id=problem_id,
                algorithm=algorithm,
                universe_size=universe_size,
                num_test_cases=num_test_cases,
                metadata=simulator_metadata,
                target_cardinality=target_cardinality,
                iteration=iteration,
                stage=stage,
                store_attempts=store_attempts,
            )

    def _infer_target_cardinality(
        self,
        key: Any,
        metadata_block: dict[str, Any],
    ) -> int | None:
        """
        Infer the target cardinality associated with a nested metadata block.

        For cardinality sweep algorithms, the dictionary key is often the
        target cardinality K. If the key is not an integer, the method also
        checks common metadata fields.
        """

        if isinstance(key, int):
            return key

        hamiltonian_metadata = metadata_block.get("hamiltonian_metadata", {})

        for field_name in ("target_cardinality", "cardinality", "K"):
            value = metadata_block.get(field_name)

            if isinstance(value, int):
                return value

            value = hamiltonian_metadata.get(field_name)

            if isinstance(value, int):
                return value

        return None

    def _infer_iteration(
        self,
        key: Any,
        metadata_block: dict[str, Any],
    ) -> int | None:
        """
        Infer the recursive or iterative step associated with a metadata block.

        This is mainly useful for recursive PUBO formulations, where each
        iteration may generate a different QUBO after adding exclusion terms.
        """

        for field_name in ("iteration", "step", "recursive_iteration"):
            value = metadata_block.get(field_name)

            if isinstance(value, int):
                return value

        if isinstance(key, str):
            lowered = key.lower()

            for prefix in ("iteration_", "iter_", "step_"):
                if lowered.startswith(prefix):
                    suffix = lowered.removeprefix(prefix)

                    if suffix.isdigit():
                        return int(suffix)

        return None

    def _infer_stage(
        self,
        key: Any,
        metadata_block: dict[str, Any],
    ) -> str | None:
        """
        Infer a human-readable stage name for a nested metadata block.

        The stage field can be used to distinguish different internal QUBOs
        produced by the same algorithm. If no stage is explicitly provided, a
        string version of the metadata key is used when appropriate.
        """

        for field_name in ("stage", "phase", "label"):
            value = metadata_block.get(field_name)

            if isinstance(value, str):
                return value

        if isinstance(key, str):
            return key

        return None

    def num_embedding_records(self) -> int:
        """
        Return the number of stored embedding benchmark records.
        """

        return len(self.embedding_records)

    def num_attempt_records(self) -> int:
        """
        Return the number of stored per-attempt benchmark records.
        """

        return len(self.attempt_records)

    @staticmethod
    def _write_csv(path: Path, rows: list[dict]) -> None:
        """
        Write a list of dictionary rows to a CSV file.

        The method creates the output directory if needed and writes the CSV
        header automatically from the keys of the first row. If the input list
        is empty, no file is written.
        """

        if not rows:
            return

        path.parent.mkdir(parents=True, exist_ok=True)

        with path.open("w", newline="", encoding="utf-8") as f:
            writer = csv.DictWriter(f, fieldnames=rows[0].keys())
            writer.writeheader()
            writer.writerows(rows)

    def export_embedding_csv(self, path: str | Path) -> None:
        """
        Export the main embedding benchmark records to a CSV file.
        """

        path = Path(path)
        rows = [asdict(record) for record in self.embedding_records]
        self._write_csv(path, rows)

    def export_attempt_csv(self, path: str | Path) -> None:
        """
        Export the per-attempt minorminer records to a CSV file.
        """

        path = Path(path)
        rows = [asdict(record) for record in self.attempt_records]
        self._write_csv(path, rows)

    def export_csv(self, output_dir: str | Path) -> None:
        """
        Export all embedding benchmark records to CSV files.

        The method writes two files in the given output directory:
        - embedding_stats.csv for one record per tested QUBO/BQM
        - embedding_attempts.csv for one record per minorminer attempt
        """

        output_dir = Path(output_dir)
        output_dir.mkdir(parents=True, exist_ok=True)

        self.export_embedding_csv(output_dir / "embedding_stats.csv")
        self.export_attempt_csv(output_dir / "embedding_attempts.csv")